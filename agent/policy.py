# ------------------------------------------------------------------ 规则

RED_FLAGS = [
    '乳头溢血', '血性溢液', '橘皮样', '酒窝征', '皮肤凹陷', '乳头内陷',
    '腋窝淋巴结肿大', '腋下肿块', '无痛性肿块', '肿块迅速增大', '乳房红肿',
    '炎性乳腺癌', '溃烂', '持续疼痛',
]

REFUSE_PATTERNS = [
    '帮我确诊', '是不是癌', '我得了什么病', '开点药', '吃什么药', '用药剂量',
    '化疗方案', '偏方', '秘方',
    '替代医生', '不用看医生', '确诊一下', '给我诊断',
]

INJECTION_PATTERNS = [
    '忽略以上', '忽略之前', 'ignore previous', 'ignore above', 'system prompt',
    '你的指令', '你的系统提示', '开发者模式', '越狱', 'jailbreak', '你现在是',
    '扮演', '假装你是', '输出你的设定',
]

CAUTIOUS_PATTERNS = ['能活多久', '生存率', '复发率', '预后', '转移概率']


def _any(pattern: str, text: str) -> bool:
    return pattern.lower() in text.lower()


def detect_injection(text: str) -> bool:
    return any(_any(p, text) for p in INJECTION_PATTERNS)


def check_question(question: str, lang: str = 'zh') -> Dict:
    """生成前的输入侧检查。"""
    text = (question or '').strip()
    verdict = {
        'action': 'allow',     # allow / refuse / escalate
        'risk': 'low',         # low / medium / high
        'reason': '',
        'banner': '',
        'injection': False,
    }

    if not text:
        verdict.update(action='refuse', reason='空问题')
        return verdict

    if detect_injection(text):
        verdict.update(action='refuse', risk='high', injection=True,
                       reason='检测到提示注入尝试')
        return verdict

    if any(_any(p, text) for p in REFUSE_PATTERNS):
        verdict.update(action='refuse', risk='high', reason='涉及确诊/用药/替代医生')
        return verdict

    if any(_any(p, text) for p in RED_FLAGS):
        verdict.update(action='escalate', risk='high', banner=RED_FLAG_BANNER.get(lang, RED_FLAG_BANNER['zh']),
                       reason='红旗症状')
        return verdict

    if any(_any(p, text) for p in CAUTIOUS_PATTERNS):
        verdict.update(risk='medium', reason='预后类问题，需谨慎表述')

    return verdict


_NUM_RE = re.compile(r'-?\d+(?:\.\d+)?')


def extract_numbers(text: str) -> List[float]:
    values = []
    for raw in _NUM_RE.findall(text or ''):
        try:
            values.append(float(raw))
        except ValueError:
            continue
    return values


def fact_numbers(facts: List[Dict]) -> List[float]:
    """把 facts 里所有数值摊平，供对账使用。"""
    out: List[float] = []

    def walk(node):
        if isinstance(node, bool):
            return
        if isinstance(node, (int, float)):
            out.append(float(node))
        elif isinstance(node, str):
            for token in _NUM_RE.findall(node):
                try:
                    out.append(float(token))
                except ValueError:
                    pass
        elif isinstance(node, dict):
            for value in node.values():
                walk(value)
        elif isinstance(node, (list, tuple)):
            for value in node:
                walk(value)

    walk(facts)
    return out


def inject_disclaimer(answer_md: str, lang: str = 'zh') -> str:
    """由模板注入免责声明（模型无权省略）。"""
    text = (answer_md or '').rstrip()
    note = DISCLAIMER.get(lang, DISCLAIMER['zh'])
    if note in text:
        return text
    return text + '\n\n---\n\n> ' + note


def apply_banner(answer_md: str, banner: str) -> str:
    if not banner:
        return answer_md
    return banner + '\n\n' + (answer_md or '')


def sanitize_untrusted(text: str, limit: int = 1200) -> str:
    """把上传内容包成"明确的数据区"，防止间接注入。"""
    clipped = (text or '')[:limit]
    clipped = clipped.replace('<<<', '<').replace('>>>', '>')
    return '<<<UNTRUSTED_DATA>>>\n' + clipped + '\n<<<END_UNTRUSTED_DATA>>>'


def check_output(answer_md: str, citations: List[str], risk: str,
                 lang: str = 'zh') -> Tuple[str, List[str]]:
    """生成后的输出侧检查，返回 (处理后的文本, 问题列表)。"""
    issues: List[str] = []
    text = answer_md or ''

    if not text.strip():
        issues.append('empty_answer')

    if risk == 'high' and not citations:
        issues.append('high_risk_without_citation')

    # 医学断言里出现"确诊/一定是"这类绝对化措辞，降级为建议性表述
    for word in ('确诊为', '可以确诊', '一定是', '肯定是'):
        if word in text:
            text = text.replace(word, '提示')
            issues.append('absolute_wording:%s' % word)

    # 未登录/越权提示不应该出现在正文里
    for word in ('Traceback', 'sqlite3.', 'password_hash'):
        if word in text:
            text = text.replace(word, '')
            issues.append('leak:%s' % word)

    return text, issues
