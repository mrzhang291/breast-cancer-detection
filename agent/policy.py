"""医疗护栏与权限模型。

两条铁律：
    1. 免责声明由模板注入，绝不由模型生成（防止模型"忘记写"）。
    2. 红旗症状、越界请求、提示注入在进入生成前就被拦截，而不是靠 prompt 约束。
"""
import re
from typing import Dict, List, Tuple

# ------------------------------------------------------------------ 权限

ROLE_PERMISSIONS = {
    1: {'*'},  # 超级管理员
    2: {'predict', 'explain', 'records:read', 'stats:read',
        'knowledge:read', 'cases:read', 'report', 'export'},  # 普通管理员
    3: {'predict', 'explain', 'records:read', 'stats:read',
        'knowledge:read', 'cases:read'},  # 医生用户
}

# 可以查看他人数据的角色
CROSS_USER_ROLES = {1, 2}


def can_use_tool(ctx, permission: str) -> bool:
    perms = ROLE_PERMISSIONS.get(int(getattr(ctx, 'role_id', 3) or 3), ROLE_PERMISSIONS[3])
    return '*' in perms or permission in perms


def can_view_other_users(ctx) -> bool:
    return int(getattr(ctx, 'role_id', 3) or 3) in CROSS_USER_ROLES


