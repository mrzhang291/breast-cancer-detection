def match(question: str) -> Optional[Dict]:
    text = (question or '').lower()
    best = None
    best_hits = 0
    for item in FAQ:
        hits = sum(1 for word in item['keywords'] if word in text)
        if hits > best_hits:
            best, best_hits = item, hits
    return best if best_hits >= 1 else None
